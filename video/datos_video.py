"""
The numbers the video shows, taken from the case's own files instead of typed by hand.

    python video/datos_video.py

Writes video/composicion/assets/datos.js (`window.DATOS = {...}`), loaded by index.html. A .js
and not a .json because a composition must not fetch anything while it renders: every frame has
to come out the same.

The rule: every number on screen comes from here, and here it comes from the case's files
(salidas/tablas/ first, datos/limpios/ when no aggregated table has it). One function per
scene that needs data. When a scene mirrors a figure, compute it exactly the way
notebooks/graficos.py does, and add an assert on the base it relies on: if the analysis ever
changes, the script stops instead of the video quietly showing an old number.

That is also how the first case found two overstatements in its own published findings:
recomputing the data behind each scene, over all the genres instead of the four a check had
used. Do this before recording, not after.
"""

from pathlib import Path
import json

RAIZ = Path(__file__).resolve().parents[1]
TABLAS = RAIZ / "salidas" / "tablas"
DESTINO = Path(__file__).resolve().parent / "composicion" / "assets" / "datos.js"


def escena_1() -> dict:
    """The hook's counter. Replace with the case's real count, read from its files. Example:

        import pandas as pd
        tabla = pd.read_csv(TABLAS / "<table>.csv")
        return {"total": int(tabla["n"].sum()), "label": "rows in the raw file"}
    """
    return {"total": 125855, "label": "<what is being counted>"}


def main() -> None:
    datos = {"hook": escena_1()}
    texto = json.dumps(datos, indent=2, ensure_ascii=False)
    DESTINO.write_text(
        "// Generated by video/datos_video.py. Do not edit by hand.\n"
        f"window.DATOS = {texto};\n",
        encoding="utf-8",
    )
    print(f"-> {DESTINO.relative_to(RAIZ)}")


if __name__ == "__main__":
    main()
